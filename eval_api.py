"""
Judge-calibration review tool — standalone service, self-hosted equivalent
of the claude.ai Artifact version. Serves the static case data (generated by
scripts/build_judge_calibration_app.py) plus a small review API backed by
eval_review_store.py. No patient data, no DB — same "small team tool" shape
as docs_api.py's /eka-review.

Run standalone: .venv/bin/python -m uvicorn eval_api:app --host 0.0.0.0 --port 8200
"""
import json
import os

from dotenv import load_dotenv
from fastapi import Depends, FastAPI, HTTPException, Request
from fastapi.responses import HTMLResponse, RedirectResponse
from pydantic import BaseModel
from sqlalchemy.orm import Session

import eval_review_store
import database as db
from dependencies import get_db, is_team_session, TEAM_COOKIE_NAME

load_dotenv()

app = FastAPI(title="Nutribot Judge Calibration")

TEAM_LOGIN_URL = "https://nutribot.computationalrd.com/team/login"


def verify_api_key(request: Request, database: Session = Depends(get_db)) -> None:
    # Only a signed-in team session (see /team/login on the nutribot
    # service) authenticates here — no standing shared secret anymore.
    if not is_team_session(request, database):
        raise HTTPException(status_code=401, detail="Not signed in — visit " + TEAM_LOGIN_URL)


@app.get("/whoami")
def whoami(request: Request, database: Session = Depends(get_db)):
    client = db.get_client_by_key(database, request.cookies.get(TEAM_COOKIE_NAME))
    if not client:
        raise HTTPException(status_code=401, detail="Not signed in")
    return {"name": client.client_name}


_APP_DIR = os.path.dirname(os.path.abspath(__file__))
_APP_HTML_PATH = os.path.join(_APP_DIR, "eval", "judge_calibration_app.html")
_CASES_PATH = os.path.join(_APP_DIR, "data", "judge_calibration_cases.json")

# Loaded once at import — cases only change via re-running the build script,
# which is a deploy-time action (service restart already required to pick up
# code changes), so a live mtime-cache like eval_review_store's isn't needed here.
with open(_CASES_PATH, encoding="utf-8") as f:
    _CASES = json.load(f)


class ReviewSubmission(BaseModel):
    judge_key: str
    case_id: int
    reviewer: str
    verdict: str
    agree: str | None = None
    notes: str = ""


@app.get("/")
def index(request: Request, database: Session = Depends(get_db)):
    # Gate the page itself, not just its data calls — visiting this URL
    # without a signed-in team session bounces straight to sign-in instead
    # of rendering a page that just sits there locked.
    if not is_team_session(request, database):
        return RedirectResponse(url=f"{TEAM_LOGIN_URL}?next=https://eval.computationalrd.com/")
    with open(_APP_HTML_PATH, encoding="utf-8") as f:
        return HTMLResponse(content=f.read())


@app.get("/api/cases", dependencies=[Depends(verify_api_key)])
def get_cases() -> dict:
    return _CASES


@app.get("/api/reviews", dependencies=[Depends(verify_api_key)])
def get_reviews() -> dict:
    return eval_review_store.all_reviews()


# ---------------------------------------------------------------------------
# Clinical rule sign-off — NOT judge calibration. These are the safety rules
# myheart_db.py applies to My Heart Coach app users (2026-10-06); a clinician
# approves/changes/rejects each one. Rule text is read from myheart_db's own
# constants so the page always shows what the bot actually does. Reviews share
# eval_review_store under the "rule:" key prefix. Ids are fixed — append only.
# ---------------------------------------------------------------------------

def _rule_items() -> list[dict]:
    import myheart_db as mh

    def floor(level):
        return ", ".join(c for c, lv in mh._LEVEL_FLOOR.items() if lv == level)

    def restr(cond):
        return ", ".join(mh._DERIVED_RESTRICTIONS[cond])

    app_says = "The My Heart Coach app's risk_level is L0 for almost every user, including high-risk ones."
    return [
        {"id": 1, "group": "Personalization level floor",
         "rule": f"Any of: {floor('L3')} → level is at least L3 (medical oversight only, emergency education).",
         "why": app_says + " A higher app level is always kept."},
        {"id": 2, "group": "Personalization level floor",
         "rule": f"Any of: {floor('L2')} → level is at least L2 (low intensity, strict stop conditions).",
         "why": app_says + " A higher app level is always kept."},
        {"id": 3, "group": "Derived dietary restriction",
         "rule": f"Chronic kidney disease → {restr('Chronic kidney disease')}",
         "why": "The app has no dietary-restriction field. Applied to anyone who ticks 'poor kidney function', regardless of stage or serum potassium."},
        {"id": 4, "group": "Derived dietary restriction",
         "rule": f"Hypertension → {restr('Hypertension')}",
         "why": "The app has no dietary-restriction field."},
        {"id": 5, "group": "Derived dietary restriction",
         "rule": f"Heart failure → {restr('Heart failure')}",
         "why": "No fluid volume is set — the bot defers the exact limit to the care team."},
        {"id": 6, "group": "Derived dietary restriction",
         "rule": f"Diabetes → {restr('Diabetes')}",
         "why": "The app has no dietary-restriction field."},
        {"id": 7, "group": "Derived dietary restriction",
         "rule": "Warfarin in the medicine list → Consistent vitamin K intake (on warfarin)",
         "why": "Food–drug interaction: large swings in leafy-green intake change INR."},
        {"id": 8, "group": "Condition mapping",
         "rule": "App answer 'poor kidney function' (medicine_history.is_poor_kidney_function) → treated as 'Chronic kidney disease'",
         "why": "Needed so kidney/potassium guidelines are retrieved. Means a self-report is treated as diagnosed CKD."},
    ]


@app.get("/api/rules", dependencies=[Depends(verify_api_key)])
def get_rules() -> dict:
    return {"rules": _rule_items()}


# ---------------------------------------------------------------------------
# Sentiment sign-off (2026-11-04) — same APPROVE/CHANGE/REJECT flow as the
# rules above, under the "sentiment:" key prefix. Text is read live from
# sentiment.py and eval/test_sentiment.py so the page shows what the bot
# actually does. No patient data: the calibration messages are
# developer-written. Ids are fixed — append only (calibration case i → 100+i,
# so eval/test_sentiment.CASES is append-only too).
# ---------------------------------------------------------------------------

def _sentiment_items() -> list[dict]:
    import importlib.util
    import sentiment as s

    spec = importlib.util.spec_from_file_location(
        "test_sentiment", os.path.join(_APP_DIR, "eval", "test_sentiment.py"))
    ts = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(ts)

    items = [
        {"id": 1, "group": "Crisis reply (fixed text)", "rule": s.CRISIS_RESPONSE,
         "why": "Sent word-for-word when a patient uses self-harm or suicide language. Please check the helpline "
                "numbers are correct and current. The bot never contacts anyone itself. It only gives the patient "
                "numbers to call and flags the turn for the team on the /team/sentiment dashboard."},
        {"id": 2, "group": "Crisis trigger phrases",
         "rule": "Any of these must trigger the crisis reply: " + "; ".join(f"“{t}”" for t in ts.CRISIS_LINES),
         "why": "Matched by a fixed keyword pattern (English + Malay), not the AI. For CHANGE, list phrases "
                "that are missing or that should not trigger it."},
    ]
    for i, state in enumerate(["distress", "low_mood", "anxious", "frustrated", "disengaged", "confused", "motivated"]):
        items.append({
            "id": 10 + i, "group": f"Tone rule: {state.replace('_', ' ')}",
            "rule": s.TONE_GUIDANCE[state],
            "why": "Added to the bot's instructions when a patient's message reads as " + state.replace("_", " ")
                   + ". On every tone rule the bot must not name the feeling or ask how the patient feels.",
        })
    for i, (msg, expected, hist) in enumerate(ts.CASES):
        items.append({
            "id": 100 + i, "group": "Calibration label",
            "rule": f"“{msg}” → {expected.replace('_', ' ')}",
            "why": ("Earlier in the chat: " + " / ".join(
                        l[len("Patient: "):] for l in hist.splitlines() if l.startswith("Patient: ")) + ". "
                    if hist else "")
                   + "Is this the right label? Used to check the classifier (eval/test_sentiment.py). For CHANGE, "
                     "write the correct label: motivated, anxious, frustrated, low mood, confused, disengaged, distress or neutral.",
        })
    return items


@app.get("/api/sentiment-signoff", dependencies=[Depends(verify_api_key)])
def get_sentiment_signoff() -> dict:
    return {"items": _sentiment_items()}


@app.post("/api/reviews", dependencies=[Depends(verify_api_key)])
def post_review(submission: ReviewSubmission) -> dict:
    return eval_review_store.add_review(
        submission.judge_key,
        submission.case_id,
        submission.reviewer,
        submission.verdict,
        submission.agree,
        submission.notes,
    )
